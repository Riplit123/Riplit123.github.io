function escapeHtml(str) {
    if (str == null) return '';
    return String(str)
        .replace(/&/g, '&amp;')
        .replace(/</g, '&lt;')
        .replace(/>/g, '&gt;')
        .replace(/"/g, '&quot;')
        .replace(/'/g, '&#039;');
}

function getMedia(project) {
    if (Array.isArray(project.media) && project.media.length) {
        return project.media;
    }
    if (Array.isArray(project.images) && project.images.length) {
        return project.images.map(src => ({ type: 'image', src }));
    }
    return [];
}

function buildVideoEmbed(url) {
    if (!url) return null;

    
    let yt = url.match(/(?:youtube\.com\/(?:watch\?v=|embed\/)|youtu\.be\/)([a-zA-Z0-9_-]{11})/);
    if (yt) {
        return `https://www.youtube.com/embed/${yt[1]}?rel=0`;
    }

    
    let vm = url.match(/vimeo\.com\/(?:video\/)?(\d+)(?:\/([a-zA-Z0-9]+))?/);
    if (vm) {
        const id = vm[1];
        const hash = vm[2];
        return hash
            ? `https://player.vimeo.com/video/${id}?h=${hash}`
            : `https://player.vimeo.com/video/${id}`;
    }

    
    
    let vkExt = url.match(/video_ext\.php\?[^"'\s]+/);
    if (vkExt) {
        // Уже готовая embed-ссылка
        return url.startsWith('http') ? url : `https://vk.com/${vkExt[0]}`;
    }
    let vk = url.match(/(?:vk\.com|vkvideo\.ru)\/video(-?\d+)_(\d+)(?:%2F|\/|\?.*?hash=)?([a-zA-Z0-9]+)?/);
    if (vk) {
        const oid = vk[1];   
        const id = vk[2];    
        const hash = vk[3];  
        let embed = `https://vk.com/video_ext.php?oid=${oid}&id=${id}&hd=2`;
        if (hash) embed += `&hash=${hash}`;
        return embed;
    }

    return null;
}


function getVideoThumb(item) {
    if (item.thumb) return item.thumb;
    let yt = (item.url || '').match(/(?:youtube\.com\/(?:watch\?v=|embed\/)|youtu\.be\/)([a-zA-Z0-9_-]{11})/);
    if (yt) {
        return `https://img.youtube.com/vi/${yt[1]}/hqdefault.jpg`;
    }
    return null;
}


function renderProjects() {
    const grid = document.getElementById('projectsGrid');
    if (!grid) {
        console.error('❌ Элемент #projectsGrid не найден в HTML!');
        return;
    }

    if (!projectsData || projectsData.length === 0) {
        grid.innerHTML = '<p style="color:var(--text-secondary);grid-column:1/-1;">Проектов пока нет.</p>';
        return;
    }

    grid.innerHTML = projectsData.map((project, index) => `
        <div class="project-card" data-index="${index}">
            <div class="project-thumb-wrapper">
                <img src="${escapeHtml(project.thumbnail || '')}"
                     alt="${escapeHtml(project.title)}"
                     class="project-thumb"
                     loading="lazy"
                     onerror="this.style.display='none';this.nextElementSibling.style.display='flex';">
                <div class="project-thumb-placeholder" style="display:none;">
                    <i class="fas fa-image"></i>
                </div>
            </div>
            <div class="project-info">
                <div class="project-title">${escapeHtml(project.title)}</div>
                <div class="project-short-desc">${escapeHtml(project.shortDesc || '')}</div>
            </div>
        </div>
    `).join('');

    grid.querySelectorAll('.project-card').forEach(card => {
        card.addEventListener('click', () => {
            openModal(parseInt(card.dataset.index));
        });
    });
}

// ===== ОТКРЫТИЕ МОДАЛКИ =====
function openModal(index) {
    const project = projectsData[index];
    if (!project) return;

    const media = getMedia(project);

    let html = `<h3 class="modal-title">${escapeHtml(project.title)}</h3>`;

        if (Array.isArray(project.tech) && project.tech.length) {
        const chips = project.tech
            .map(t => `<span class="modal-tech-chip">${escapeHtml(t)}</span>`)
            .join('');
        html += `
            <div class="modal-tech">
                <div class="modal-tech-list">${chips}</div>
            </div>
        `;
    }

    // Описание проекта
    if (project.shortFullDesc || project.restFullDesc) {
        const shortPart = escapeHtml(project.shortFullDesc || '');
        const restPart = escapeHtml(project.restFullDesc || '');

        html += `<div class="modal-desc">`;
        html += `<span>${shortPart}</span>`;

        if (restPart) {
            html += `<span class="modal-desc-dots" id="descDots">...</span>`;
            html += `<span class="modal-desc-rest is-hidden" id="descRest">\n\n${restPart}</span>`;
            html += `</div>`;
            html += `<button type="button" class="modal-desc-toggle" id="descToggle">Полное описание</button>`;
        } else {
            html += `</div>`;
        }
    } else if (project.fullDesc) {
        html += `<div class="modal-desc">${escapeHtml(project.fullDesc)}</div>`;
    }

    if (media.length) {
        const thumbsHtml = media.map((item, i) => {
            if (item.type === 'video') {
                const vthumb = getVideoThumb(item);
                const inner = vthumb
                    ? `<img src="${escapeHtml(vthumb)}" alt="video" loading="lazy">`
                    : `<div class="gallery-thumb-novideo"><i class="fas fa-film"></i></div>`;
                return `
                    <button class="gallery-thumb ${i === 0 ? 'active' : ''}" data-index="${i}">
                        ${inner}
                        <span class="gallery-thumb-play"><i class="fas fa-play"></i></span>
                    </button>
                `;
            }
            return `
                <button class="gallery-thumb ${i === 0 ? 'active' : ''}" data-index="${i}">
                    <img src="${escapeHtml(item.src)}" alt="thumb"
                         loading="lazy"
                         onerror="this.style.display='none';this.parentElement.classList.add('gallery-thumb-broken');">
                </button>
            `;
        }).join('');

        html += `
            <div class="gallery">
                <div class="gallery-thumbs">${thumbsHtml}</div>
                <div class="gallery-main" id="galleryMain"></div>
            </div>
        `;
    }

    document.getElementById('modalDynamicContent').innerHTML = html;
    document.getElementById('projectModal').classList.add('active');
    document.body.style.overflow = 'hidden';

        if (media.length) {
        initGallery(media);
    }

    // Кнопка «Полное описание / Свернуть»
    initDescToggle();
}

// ===== СВОРАЧИВАЕМОЕ ОПИСАНИЕ =====
function initDescToggle() {
    const btn = document.getElementById('descToggle');
    const dots = document.getElementById('descDots');
    const rest = document.getElementById('descRest');
    if (!btn || !rest) return;

    btn.addEventListener('click', () => {
        const isHidden = rest.classList.contains('is-hidden');
        if (isHidden) {
            rest.classList.remove('is-hidden');
            if (dots) dots.style.display = 'none';
            btn.textContent = 'Свернуть описание';
        } else {
            rest.classList.add('is-hidden');
            if (dots) dots.style.display = 'inline';
            btn.textContent = 'Полное описание';
        }
    });
}

// ===== ГАЛЕРЕЯ =====
function initGallery(media) {
    const mainEl = document.getElementById('galleryMain');
    const thumbs = document.querySelectorAll('.gallery-thumb');
    if (!mainEl) return;

    function showItem(i) {
        const item = media[i];
        if (!item) return;

        if (item.type === 'video') {
            const embed = buildVideoEmbed(item.url);
            if (embed) {
                mainEl.innerHTML = `
                    <div class="gallery-video">
                        <iframe src="${embed}"
                                allow="autoplay; fullscreen; picture-in-picture"
                                allowfullscreen></iframe>
                    </div>
                `;
            } else {
                // Ссылка не распознана — даём кнопку на внешний переход
                mainEl.innerHTML = `
                    <div class="gallery-video-error">
                        <i class="fas fa-triangle-exclamation"></i>
                        <p>Не удалось встроить видео.</p>
                        <a href="${escapeHtml(item.url || '#')}" target="_blank" class="gallery-video-link">
                            Открыть на видеохостинге
                        </a>
                    </div>
                `;
            }
        } else {
            // Изображение
            mainEl.innerHTML = `
                <img src="${escapeHtml(item.src)}" alt="фото проекта" loading="lazy"
                     onerror="this.style.display='none';this.parentElement.classList.add('gallery-main-broken');">
            `;
        }

        // Подсветка активной миниатюры
        thumbs.forEach((t, idx) => t.classList.toggle('active', idx === i));
    }

    // Клик по миниатюре
    thumbs.forEach(thumb => {
        thumb.addEventListener('click', () => {
            showItem(parseInt(thumb.dataset.index));
        });
    });

    // Показываем первый элемент
    showItem(0);
}

