function closeModal() {
    const modal = document.getElementById('projectModal');
    modal.classList.remove('active');
    // Очищаем содержимое, чтобы остановить воспроизведение видео
    document.getElementById('modalDynamicContent').innerHTML = '';
    document.body.style.overflow = '';
}

// ===== МОБИЛЬНОЕ МЕНЮ (БУРГЕР) =====
function initMobileMenu() {
    const toggle = document.getElementById('navToggle');
    const links = document.getElementById('navLinks');
    if (!toggle || !links) return;

    function closeMenu() {
        links.classList.remove('open');
        toggle.classList.remove('open');
        toggle.setAttribute('aria-expanded', 'false');
    }

    function toggleMenu() {
        const isOpen = links.classList.toggle('open');
        toggle.classList.toggle('open', isOpen);
        toggle.setAttribute('aria-expanded', isOpen ? 'true' : 'false');
    }

    // Открытие/закрытие по кнопке
    toggle.addEventListener('click', (e) => {
        e.stopPropagation();
        toggleMenu();
    });

    // Закрытие при клике на пункт меню
    links.querySelectorAll('.nav-link').forEach(link => {
        link.addEventListener('click', closeMenu);
    });

    // Закрытие при клике вне меню
    document.addEventListener('click', (e) => {
        if (links.classList.contains('open') &&
            !links.contains(e.target) &&
            !toggle.contains(e.target)) {
            closeMenu();
        }
    });

    // Закрытие при возврате на десктоп-ширину
    window.addEventListener('resize', () => {
        if (window.innerWidth > 768) closeMenu();
    });
}

// ===== ИНИЦИАЛИЗАЦИЯ =====
document.addEventListener('DOMContentLoaded', function () {
    renderProjects();
    initMobileMenu();

    // Закрытие модалки по крестику
    const closeBtn = document.getElementById('closeModalBtn');
    if (closeBtn) {
        closeBtn.addEventListener('click', closeModal);
    }

    // Закрытие по клику вне контента
    window.addEventListener('click', function (e) {
        const modal = document.getElementById('projectModal');
        if (e.target === modal) closeModal();
    });

    // Закрытие по ESC
    window.addEventListener('keydown', function (e) {
        if (e.key === 'Escape') closeModal();
    });

    // Плавный скролл по навигации
    document.querySelectorAll('.nav-link').forEach(link => {
        link.addEventListener('click', function (e) {
            e.preventDefault();
            const target = document.querySelector(this.getAttribute('href'));
            if (target) target.scrollIntoView({ behavior: 'smooth' });
        });
    });

    // Копирование контактов
    document.querySelectorAll('.copy-icon').forEach(icon => {
        icon.addEventListener('click', function (e) {
            e.stopPropagation();
            const text = this.dataset.copy;

            const showTooltip = () => {
                const tooltip = document.createElement('div');
                tooltip.className = 'copy-tooltip';
                tooltip.textContent = 'Скопировано!';
                document.body.appendChild(tooltip);
                tooltip.style.left = e.clientX + 'px';
                tooltip.style.top = (e.clientY - 40) + 'px';
                setTimeout(() => tooltip.remove(), 1500);
            };

            if (navigator.clipboard && navigator.clipboard.writeText) {
                navigator.clipboard.writeText(text)
                    .then(showTooltip)
                    .catch(err => console.error('Ошибка копирования:', err));
            } else {
                // Запасной вариант для старых браузеров / http
                const ta = document.createElement('textarea');
                ta.value = text;
                ta.style.position = 'fixed';
                ta.style.opacity = '0';
                document.body.appendChild(ta);
                ta.select();
                try { document.execCommand('copy'); showTooltip(); }
                catch (err) { console.error('Ошибка копирования:', err); }
                ta.remove();
            }
        });
    });
});
